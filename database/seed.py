def seed_if_empty():
    if User.query.first():
        return
    try:
        _seed()
        db.session.commit()
    except Exception:
        db.session.rollback()
        # Also wipe any partial writes from disk (checkpoint commits above
        # inside _seed); the caller will re-attempt or surface the error.
        import traceback
        traceback.print_exc()
        raise


